-- MeetTennis: tablas base para instalar el proyecto en un Supabase nuevo.
-- Ejecutar antes de 02_disponibilidad_partidos.sql.
-- Las tablas existentes se conservan; este script no agrega usuarios de ejemplo.
BEGIN;

CREATE TABLE IF NOT EXISTS public.usuario (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  nombre text NOT NULL,
  apellido text NOT NULL,
  fecha_nacimiento date NOT NULL,
  genero text NOT NULL,
  nivel text NOT NULL,
  avatar_url text
);

CREATE TABLE IF NOT EXISTS public.canchas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL,
  direccion text NOT NULL,
  latitud double precision,
  longitud double precision
);

-- Solo el backend, mediante service_role, accede a estas tablas.
ALTER TABLE public.usuario ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.canchas ENABLE ROW LEVEL SECURITY;

COMMIT;
